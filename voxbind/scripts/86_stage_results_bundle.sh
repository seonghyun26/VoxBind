#!/usr/bin/env bash
# 86_stage_results_bundle.sh
#   Stage everything THIS BOX (svr12) generated into results/, ready for
#   results/dropbox_push.sh -> dropbox:/박성현/VoxBind/results.
#
#   WHAT IS ON THIS BOX AND NOWHERE ELSE
#     * the four CrossDocked generation arms in voxbind/exps/ (260827 / 260831 /
#       260902 / 260905) -- samples.sdf + per-target metrics.json (vina + posecheck
#       + posebusters, v2 schema) + the sampling logs;
#     * the five published baselines RE-GENERATED here under our protocol, packed
#       into targetdiff meta format at ../baselines/_meta/<M>{,_part2,_gap}.pt
#       (`mol`/`smiles`/`ligand_filename`/`pred_pos` per molecule -- the molecules
#       themselves, not a summary) plus their eval summaries.
#     None of it is in git (exps/ and results/ are ignored) and none of the
#     generation arms is in model_zoo/, so Dropbox is the only copy that survives
#     a scratch cleanup on a 94%-full shared disk.
#
#   WHAT IS DELIBERATELY LEFT OUT
#     * .vina_cache/ under every target dir -- pdbqt/pqr/pdb receptor-prep scratch,
#       ~90% of the sample-dir bytes, regenerated by the docking script in minutes;
#     * baselines/_out/ (97 GB of raw generator output) -- _meta/*.pt is the same
#       molecules in 69 MB;
#     * the 1.3-1.7 GB generator checkpoints -- see the note at the end of the run.
#
#   Idempotent: rsync/cp -u only, nothing is deleted, re-run after a new arm lands.
#
#   Usage:  bash voxbind/scripts/86_stage_results_bundle.sh [-n]
#             -n / --dry-run          list what would be staged, copy nothing
#           WITH_BASELINE_EVAL=1 ...  also stage the per-pocket baseline eval
#                                     (_eval/*.pt + _posebusters + _posecheck,
#                                      ~630 MB; days of CPU to recompute)
#           WITH_LEGACY=1 ...         also stage the superseded svr12 sets: the
#                                     CBGBench export, the March x-ray PoC and the
#                                     early un-evaluated smoke runs (~131 MB).
#                                     NOT uploaded as of 2026-09-09 -- deliberate.
set -euo pipefail

ROOT=/home/shpark/prj-denovo/Voxbind
BASE=/home/shpark/prj-denovo/baselines
VOX="$ROOT/voxbind"
RES="$ROOT/results"
T2="$RES/task2-drugdesign"
T3="$RES/task3-mcp"
NB="$ROOT/notebook/html/260910"
WITH_BASELINE_EVAL="${WITH_BASELINE_EVAL:-0}"
WITH_LEGACY="${WITH_LEGACY:-0}"

DRY=0
for a in "$@"; do case "$a" in -n|--dry-run) DRY=1 ;; esac; done
run() { if [[ "$DRY" == 1 ]]; then echo "   [dry] $*"; else "$@"; fi; }

# label | folder under task2-drugdesign | exp dir | sample subdir
ARMS=(
  "VoxBind base (ours, ep350)|VoxBind-base-ep350|260827_voxbind_base_8gpu|samples/samples_ep350_test"
  "Fusion v4 cdgv2 warm ep100|Fusion-v4-cdgv2-warm-ep100|260831_fusion_v4_cdgv2_8gpu|samples/samples_ep100_test79"
  "Fusion v4 cdgv2 scratch ep350|Fusion-v4-cdgv2-scratch-ep350|260902_fusion_v4_cdgv2_scratch_8gpu|samples/samples_ep350_test79"
  "Fusion v4 cv2 scratch ep350|Fusion-v4-cv2-scratch-ep350|260905_fusion_v4_cv2_scratch_8gpu|samples/samples_ep350_test79"
  # Added 2026-09-12. Both were generated AND (mostly) evaluated on this box weeks ago and
  # never reached the bundle, which is exactly the drift EVAL_STATUS.md now catches.
  #   n100      the base arm re-sampled at the paper's 100 molecules/pocket instead of the
  #             shipped default of 10 -- its own folder, because n_molecules/pocket is part
  #             of the protocol and must not be silently averaged with the 10/pocket row.
  #   default   the fusion-default cv2 control; PoseBusters never ran on it (see EVAL_STATUS).
  "VoxBind base (ours, ep350, 100/pocket)|VoxBind-base-ep350-n100|260827_voxbind_base_8gpu|samples/samples_ep350_test100_n100"
  "Fusion default cv2 scratch ep350|Fusion-default-cv2-scratch-ep350|260908_fusion_default_cv2_scratch_8gpu|samples/samples_ep350_test79"
)
BASELINES=(AR Pocket2Mol DiffSBDD DecompDiff_ref_prior FuncBind)
# _meta name -> results/ folder name (the bundle already uses DecompDiff)
bl_folder() { [[ "$1" == DecompDiff_ref_prior ]] && echo DecompDiff || echo "$1"; }

echo "==> staging into $RES  (dry-run=$DRY, baseline_eval=$WITH_BASELINE_EVAL, legacy=$WITH_LEGACY)"

# ---------------------------------------------------------------- our 4 arms
for row in "${ARMS[@]}"; do
  IFS='|' read -r label folder exp sub <<<"$row"
  src="$VOX/exps/$exp/$sub"
  dst="$T2/$folder"
  if [[ ! -d "$src" ]]; then echo "!! missing, skipped: $src"; continue; fi
  n_t=$(find "$src" -maxdepth 1 -name 'target_*' -type d | wc -l)
  n_m=$(find "$src" -name samples.sdf | wc -l)
  echo "-- $label  ($n_t targets, $n_m sample files)  -> $folder/"
  run mkdir -p "$dst/samples" "$dst/run"
  # samples, minus the regenerable docking scratch
  run rsync -a --exclude '.vina_cache/' --exclude '.vina_tmp*' "$src/" "$dst/samples/"
  # the training run's identity: config + log (both < 100 KB)
  run cp -u "$VOX/exps/$exp/cfg.yaml" "$dst/run/cfg.yaml"
  [[ -d "$VOX/exps/$exp/.hydra" ]] && run rsync -a "$VOX/exps/$exp/.hydra/" "$dst/run/hydra/"
  [[ -f "$VOX/exps/$exp/train_ddp.log" ]] && run cp -u "$VOX/exps/$exp/train_ddp.log" "$dst/run/train_ddp.log"
done

# ------------------------------------------------- baselines re-generated here
for m in "${BASELINES[@]}"; do
  f=$(bl_folder "$m")
  echo "-- baseline $m -> $f/samples/meta/"
  run mkdir -p "$T2/$f/samples/meta"
  for part in "" _part2 _gap; do
    p="$BASE/_meta/${m}${part}.pt"
    [[ -f "$p" ]] && run cp -u "$p" "$T2/$f/samples/meta/"
  done
  # the bundle's SOURCE.txt said "generated samples not on this machine" -- written
  # from the reporting box. They ARE on svr12, and now they are in the bundle.
  if [[ "$DRY" == 0 ]]; then
    cat > "$T2/$f/SOURCE.txt" <<EOF
generated on svr12; the molecules are IN this bundle: samples/meta/${m}{,_part2,_gap}.pt
  targetdiff meta format -- one list per test pocket of
  {mol, smiles, ligand_filename, pred_pos}; load with torch.load(weights_only=False).
  _part2 is the second half of the 100 molecules/pocket, _gap the re-run fill.
built by  prj-denovo/baselines/_scripts/build_meta.py
from      prj-denovo/baselines/_out/${m}/   (97 GB of raw generator output, not uploaded)
code      prj-denovo/baselines/${m}/
eval      per-pocket vina/posecheck/posebusters stay in prj-denovo/baselines/_eval,
          _posebusters, _posecheck on svr12 (~630 MB; re-run 86_stage_results_bundle.sh
          with WITH_BASELINE_EVAL=1 to add them here). Aggregates are in
          ../_shared/baselines_eval/.
EOF
  else
    echo "   [dry] rewrite $f/SOURCE.txt"
  fi
  if [[ "$WITH_BASELINE_EVAL" == 1 ]]; then
    echo "   + per-pocket eval (_eval/_posebusters/_posecheck)"
    run mkdir -p "$T2/$f/eval"
    for d in "_eval/$m" "_eval/${m}_part2" "_eval/${m}_gap" "_posebusters/$m" "_posecheck/$m"; do
      [[ -d "$BASE/$d" ]] && run rsync -a "$BASE/$d/" "$T2/$f/eval/$(basename "$(dirname "$BASE/$d")")_$(basename "$d")/"
    done
  fi
done

# ------------------------------------------------- older svr12 sample sets
echo "-- VoxBind vanilla (published sigma=0.9, 100 mols/pocket) -> VoxBind-vanilla/"
# The PUBLISHED sigma=0.9 checkpoint (byte-identical to
# model_zoo/voxbind_sig0.9_crossdocked) sampled on this box at 100 molecules per
# pocket -- the 100/pocket counterpart of VoxBind-Ours, and the only vanilla row
# on this box at that protocol (the four arms ran the shipped default of 10).
# Its own top-level folder, mirroring VoxBind-Ours; the VoxBind/ folder keeps the
# reporting box's viz targets and its metrics.json untouched.
RD="$T2/VoxBind-vanilla/samples"
run mkdir -p "$RD"
run rsync -a --exclude '.vina_cache/' "$VOX/exps/reproduction/samples/res_test_100/" "$RD/"
run cp -u "$VOX/exps/reproduction/cfg.yaml" "$RD/cfg.yaml"
run cp -u "$VOX/exps/reproduction/train.log" "$RD/train.log"
if [[ "$DRY" == 0 ]]; then
  python3 "$(dirname "${BASH_SOURCE[0]}")/tools/vanilla_metrics.py" "$T2" || true
else
  echo "   [dry] write VoxBind-vanilla/metrics.json + SOURCE.txt"
fi

# ---------------------------------------------------- PoseCheck strain energy
# Per-molecule PoseCheck (torsional strain, steric clashes, interaction profile)
# for the five baselines, as run on this box by baselines/_scripts/run_posecheck.py
# -- one file per (pocket, chunk). ~10 MB for all five, and strain relaxes 50
# conformers per molecule (~60 s each), so this is days of CPU, not a re-run.
# Our own arms carry the same numbers per molecule inside samples/target_*/metrics.json
# (samples[i].posecheck), so they need nothing here.
echo "-- PoseCheck strain (5 baselines, per molecule) -> <method>/eval/posecheck/"
for m in "${BASELINES[@]}"; do
  f=$(bl_folder "$m")
  [[ -d "$BASE/_posecheck/$m" ]] || continue
  run mkdir -p "$T2/$f/eval"
  run rsync -a "$BASE/_posecheck/$m/" "$T2/$f/eval/posecheck/"
done
run mkdir -p "$T2/_shared/260910_posecheck"
for f in "$NB"/fig-posecheck/*.json "$NB"/fig-posecheck/*.py; do
  [[ -f "$f" ]] && run cp -u "$f" "$T2/_shared/260910_posecheck/"
done

# ------------------------------------------------------- FuncBind sample sets
# The FuncBind runs that live on THIS box: prj-denovo/funcbind/funcbind/exps/
# funcbind/fb_unified/eval_test_diffusion_s128_{xd,mcpp}_full_gpu0..7 -- eight
# GPU shards each, striding the target list, sampled 2026-08-01. Per target:
# samples.sdf + samples.pdb + metrics.pt + the receptor, plus samples/res/ with
# each generated molecule as its own cleaned PDB.
#   xd   -> CrossDocked, joins task2 FuncBind (whose meta .pt is already here)
#   mcpp -> macrocyclic peptides, joins task3 FuncBind-vanilla
# NOT copied: fb_unified/checkpoint.pth.tar (61.7 GB) and the nc*/probe/smoke
# sampling-parameter probes.
FB=/home/shpark/prj-denovo/funcbind/funcbind/exps/funcbind/fb_unified
if [[ -d "$FB" ]]; then
  echo "-- FuncBind sample sets (xd + mcpp, 8 GPU shards each)"
  # rsync only creates the last path component -- make the shard parents first
  run mkdir -p "$T2/FuncBind/samples/fb_unified_xd_full" \
               "$T3/FuncBind-vanilla/samples/fb_unified_mcpp_full"
  for g in 0 1 2 3 4 5 6 7; do
    x="$FB/eval_test_diffusion_s128_xd_full_gpu$g"
    m="$FB/eval_test_diffusion_s128_mcpp_full_gpu$g"
    [[ -d "$x" ]] && run rsync -a "$x/" "$T2/FuncBind/samples/fb_unified_xd_full/gpu$g/"
    [[ -d "$m" ]] && run rsync -a "$m/" "$T3/FuncBind-vanilla/samples/fb_unified_mcpp_full/gpu$g/"
  done
  if [[ "$DRY" == 0 ]]; then
    cat > "$T2/FuncBind/samples/fb_unified_xd_full/SOURCE.txt" <<'FBEOF'
FuncBind, CrossDocked eval -- sampled on svr12, 2026-08-01.

source   prj-denovo/funcbind/funcbind/exps/funcbind/fb_unified/
         eval_test_diffusion_s128_xd_full_gpu0..7
shards   eight GPU shards, each striding the 100-target test list (gpu0 takes
         target_00, 08, 16, ..., 96); gpu0-3 carry 13 targets, gpu4-7 carry 12.
         Verified 2026-09-10: 100 target dirs, no gap and no duplicate.
per target  samples.sdf (100 generated molecules) + metrics.pt. Ligand-only --
         no receptor copy and no per-molecule PDBs. (The MCPP run in
         ../../../task3-mcp/FuncBind-vanilla/ DOES write samples.pdb, the
         receptor and its CP chain, and samples/res/*.pdb; this one does not.)
per shard  samples/metrics.pt and samples/res/ -- the shard's hydra config and
         sample_fb.log, not molecules.
counts   10,000 molecules in the SDFs (100 pockets x 100). The 9,992 reported in
         ../../metrics.json is the meta/eval count: 8 molecules are dropped when
         the SDFs are packed into targetdiff meta format, all in the second half
         of the budget -- pockets 5, 11, 26, 39, 53, 84 lose one each and 70
         loses two.
weights  fb_unified/checkpoint.pth.tar, 61.7 GB -- NOT uploaded

The same molecules also reach this bundle in targetdiff meta format at
../meta/FuncBind{,_part2,_gap}.pt (5,000 + 4,992 + 0), which is what the
Vina/PoseCheck/PoseBusters numbers in ../../metrics.json were computed from.
FBEOF
    cat > "$T3/FuncBind-vanilla/samples/fb_unified_mcpp_full/SOURCE.txt" <<'FBEOF'
FuncBind, macrocyclic-peptide (MCPP) eval -- sampled on svr12, 2026-08-01.

source   prj-denovo/funcbind/funcbind/exps/funcbind/fb_unified/
         eval_test_diffusion_s128_mcpp_full_gpu0..7
shards   eight GPU shards striding the target list
per target  samples.sdf + samples.pdb, metrics.pt, the receptor (…-protein.pdb)
         and its cyclic-peptide chain (…-CP.pdb); samples/res/ holds each
         generated peptide as its own cleaned PDB
weights  fb_unified/checkpoint.pth.tar, 61.7 GB -- NOT uploaded

Filed under FuncBind-vanilla because it is the stock FuncBind checkpoint with no
receptor-ED conditioning -- the same rule the bundle's other task3 runs follow
(vanilla eval runs -> FuncBind-vanilla, curated paper-100 -> Ours-receptorED).
These runs are NOT the ones already in this folder: those are the 20260727/28
sampling_fb_* runs from the reporting box.
FBEOF
  else
    echo "   [dry] write both fb_unified SOURCE.txt"
  fi
fi

# --------------------------------------------- Reference (crystal ligands)
# The CrossDocked2020 test ligands themselves, put through the SAME Vina protocol
# on this box -- the reference energy every generated molecule is scored against
# (High-Affinity % is "beats this pocket's reference"). Always carried: its
# per-pocket eval is 1.8 MB, not the ~630 MB a generated baseline's is.
echo "-- Reference (crystal test ligands) -> Reference/"
run mkdir -p "$T2/Reference/samples/meta" "$T2/Reference/eval"
[[ -f "$BASE/_meta/reference_test.pt" ]] && run cp -u "$BASE/_meta/reference_test.pt" "$T2/Reference/samples/meta/"
[[ -d "$BASE/_eval/Reference" ]] && run rsync -a "$BASE/_eval/Reference/" "$T2/Reference/eval/per_pocket/"
if [[ "$DRY" == 0 ]]; then
  python3 - "$T2" "$BASE" <<'REFPY'
import json, sys
t2, base = sys.argv[1:3]
rows = {}
for scope, f in (("all", "summary.json"), ("density79", "summary_density79.json")):
    d = json.load(open(f"{base}/_eval/{f}"))
    rows[scope] = next((r for r in d if r.get("baseline") == "Reference"), None)
json.dump({
    "task": "drugdesign",
    "method": "Reference",
    "folder": "Reference",
    "benchmark": "CrossDocked",
    "generated_on": "svr12 (not generated -- the deposited crystal ligands, re-scored here)",
    "what": "CrossDocked2020 test-set crystal ligand of each pocket, put through the "
            "same Vina protocol as every generated molecule. This is the reference "
            "energy the High-Affinity % of every other row is measured against.",
    "vina": {s: (r or {}) for s, r in rows.items()},
    "report": "../../reports/results_drug_design.html",
}, open(f"{t2}/Reference/metrics.json", "w"), indent=2)
r = rows["density79"]
print(f"   Reference/metrics.json  (d79: score {r['vina_score_mean']:.2f} / "
      f"min {r['vina_min_mean']:.2f} / dock {r['vina_dock_mean']:.2f})")
REFPY
  cat > "$T2/Reference/SOURCE.txt" <<'REFEOF'
CrossDocked2020 test-set crystal ligands, re-scored on svr12 -- NOT generated.

samples/meta/reference_test.pt   the ligands in targetdiff meta format
eval/per_pocket/eval_*.pt        per-pocket Vina (score_only / minimize / dock) plus
                                 QED / SA / size -- 102 files, written by
                                 prj-denovo/baselines/_scripts/evaluate_from_meta_mp.py
metrics.json                     the aggregate rows, both pocket scopes

The same numbers are the "Reference" row of ../_shared/baselines_eval/summary*.json.

This is BINDING energy (Vina). Reference-ligand STRAIN energy (PoseCheck internal
energy) is NOT measured on this box: every sample run here carries reference.vina
(+ reference.posebusters on the four arms) but no reference.posecheck. The strain
reference curve in the 260910 figures is read on the reporting box from
exps/voxbind_frozenenc_atomblob7_v2p1_sig0.9/samples/full_eval_ep350.
REFEOF
else
  echo "   [dry] write Reference/metrics.json + SOURCE.txt"
fi

# ------------------------------------------------------------------- _shared
echo "-- _shared (cross-method tables, pocket definitions, eval summaries)"
run mkdir -p "$T2/_shared/260910_posebusters" "$T2/_shared/baselines_eval" "$T2/_shared/pocket_sets"
for f in posebusters_table_all.csv posebusters_table_density79.csv posebusters_table.json \
         build_posebusters_table.py pose_common.py method_colors.py; do
  [[ -f "$NB/$f" ]] && run cp -u "$NB/$f" "$T2/_shared/260910_posebusters/"
done
for f in summary.json summary_density79.json posebusters_summary.json \
         posebusters_summary_density79.json posecheck_summary.json \
         posecheck_summary_density79.json yield.json; do
  [[ -f "$BASE/_eval/$f" ]] && run cp -u "$BASE/_eval/$f" "$T2/_shared/baselines_eval/"
done
for f in density_pockets_selected.json density_pockets_92.json density_pdbe_eds.json \
         density_same_pdb.json density_tt_min.json; do
  [[ -f "$BASE/_shared_data/$f" ]] && run cp -u "$BASE/_shared_data/$f" "$T2/_shared/pocket_sets/"
done

# --------------------------------------------------- per-arm metrics.json
if [[ "$DRY" == 0 ]]; then
  echo "-- writing per-arm metrics.json (arm summary.json + the 260910 PoseBusters row)"
  python3 - "$T2" "$VOX" "$NB" <<'PY'
import json, os, sys
t2, vox, nb = sys.argv[1:4]
arms = [
    ("VoxBind base (ours, ep350)", "VoxBind-base-ep350",
     "260827_voxbind_base_8gpu", "samples/samples_ep350_test",
     "vanilla VoxBind (ICML'24 recipe), 8-GPU DDP from scratch, sigma=0.9, 350 ep -- "
     "the density-free control every fusion arm is measured against"),
    ("Fusion v4 cdgv2 warm ep100", "Fusion-v4-cdgv2-warm-ep100",
     "260831_fusion_v4_cdgv2_8gpu", "samples/samples_ep100_test79",
     "token fusion v4 + frozen CDG_v2 encoder, WARM-started from the 260827 baseline, "
     "100 ep on the 78.5k x-ray subset"),
    ("Fusion v4 cdgv2 scratch ep350", "Fusion-v4-cdgv2-scratch-ep350",
     "260902_fusion_v4_cdgv2_scratch_8gpu", "samples/samples_ep350_test79",
     "same fusion, trained FROM SCRATCH for 350 ep -- removes the warm-start drift term"),
    ("Fusion v4 cv2 scratch ep350", "Fusion-v4-cv2-scratch-ep350",
     "260905_fusion_v4_cv2_scratch_8gpu", "samples/samples_ep350_test79",
     "matched coords-only control: C_v2 encoder (no rho, no ||grad rho||) through the "
     "identical v4 fusion -- isolates the density channels"),
    # Added 2026-09-12 alongside the ARMS entries above. Neither is in the 260910
    # PoseBusters table, so posebusters_260910 lands as null for them -- deliberately:
    # a missing figure row must read as missing, not as zero.
    ("VoxBind base (ours, ep350, 100/pocket)", "VoxBind-base-ep350-n100",
     "260827_voxbind_base_8gpu", "samples/samples_ep350_test100_n100",
     "the same vanilla ep350 checkpoint re-sampled at the paper's 100 molecules per "
     "pocket instead of the shipped default of 10 -- the draw budget is part of the "
     "protocol, so it gets its own row rather than being averaged with the 10/pocket one"),
    ("Fusion default cv2 scratch ep350", "Fusion-default-cv2-scratch-ep350",
     "260908_fusion_default_cv2_scratch_8gpu", "samples/samples_ep350_test79",
     "C_v2 coords-only encoder through the DEFAULT fusion block rather than v4 -- the "
     "architecture control for the v4 fusion itself. PoseBusters has not been run on it "
     "(see results/task2-drugdesign/EVAL_STATUS.md)"),
]
tbl = json.load(open(f"{nb}/posebusters_table.json"))
rows = {scope: {r["row"]: r for r in tbl[scope]} for scope in tbl}
for label, folder, exp, sub, note in arms:
    d = f"{t2}/{folder}"
    if not os.path.isdir(d):
        continue
    summ = json.load(open(f"{d}/samples/summary.json"))["summary"]
    out = {
        "task": "drugdesign",
        "method": label,
        "folder": folder,
        "benchmark": "CrossDocked",
        "generated_on": "svr12",
        "source_run": f"voxbind/exps/{exp}",
        "source_samples": f"voxbind/exps/{exp}/{sub}",
        "what": note,
        "n_targets": summ.get("n_targets"),
        "n_molecules": summ.get("n_molecules"),
        "eval": summ,
        "posebusters_260910": {s: rows[s].get(label) for s in rows},
        "report": "../../reports/results_drug_design.html",
    }
    json.dump(out, open(f"{d}/metrics.json", "w"), indent=2)
    print(f"   {folder}/metrics.json  ({summ.get('n_targets')} targets, "
          f"{summ.get('n_molecules')} mols, vina_dock {summ.get('vina_dock_mean')})")
PY
fi

echo
echo "==> staged size:"
du -sh "$RES" 2>/dev/null || true
[[ "$DRY" == 0 ]] && du -sh "$T2"/*/ 2>/dev/null | sort -h | tail -12
cat <<'NOTE'

==> next
    bash results/dropbox_push.sh          # dry-run preview, then asks to confirm
    bash results/dropbox_push.sh -y       # non-interactive

    The generator checkpoints behind these samples are NOT in this bundle -- they
    go to the model zoo instead:  bash voxbind/scripts/87_stage_model_zoo_arms.sh
    then voxbind/model_zoo/dropbox_push.sh  (done 2026-09-09, model_zoo/gen_*).
NOTE
